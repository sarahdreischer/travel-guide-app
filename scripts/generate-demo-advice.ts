/**
 * Generate real LLM advice for the /demo trips and write it to
 * src/lib/demo-advice.generated.ts.
 *
 * The demo prefers these real answers; any category/question not present here
 * falls back to the example patterns in demo-data.ts. Re-run this whenever you
 * want to refresh the demo content (e.g. after changing demo destinations).
 *
 * Usage:
 *   npm run generate-demo-advice
 *
 * Requires OPENAI_API_KEY (and DATABASE_URL, since the shared LLM adapter also
 * caches generated advice) in .env.local.
 */

import { loadEnvConfig } from '@next/env'
loadEnvConfig(process.cwd())

import { writeFile } from 'fs/promises'
import path from 'path'

async function main() {
  // Dynamic imports AFTER env is loaded.
  const { DEMO_SEEDS } = await import('../src/lib/demo-data')
  const { CATEGORIES, getSubQuestions } = await import('../src/lib/destinations')
  const { deriveMonthRange } = await import('../src/lib/advice-store')
  const { derivebudgetRange } = await import('../src/lib/validators')
  const { LLMAdapter } = await import('../src/lib/llm-adapter')
  const { getGroupQuestions } = await import('../src/lib/category-groups')
  const { findAnswer } = await import('../src/lib/answer-lookup')

  // ISO dates for the demo seeds (relative to today, mirroring demo-data).
  const isoDate = (offsetDays: number): string => {
    const d = new Date()
    d.setHours(0, 0, 0, 0)
    d.setDate(d.getDate() + offsetDays)
    return d.toISOString().split('T')[0]
  }

  type Entry = {
    categories: Record<string, Record<string, string>>
    groupTips: Record<string, string>
  }

  const output: Record<string, Entry> = {}
  const categoriesWithQuestions = CATEGORIES.filter((c) => getSubQuestions(c).length > 0)

  for (const seed of DEMO_SEEDS) {
    console.log(`\n[${seed.destination}] generating advice…`)

    const startDate = isoDate(seed.startOffset)
    const endDate = isoDate(seed.endOffset)
    const { startMonth, endMonth } = deriveMonthRange(startDate, endDate)

    const cacheKey = {
      destination: seed.destination.toLowerCase(),
      startMonth,
      endMonth,
      travellerType: seed.travelMode.toLowerCase(),
      budgetRange: derivebudgetRange(seed.budgetUsd),
      transportMode: seed.transportMode,
      startingLocation: seed.startingLocation,
      totalBudgetUsd: seed.budgetUsd,
      transportCostIncluded: seed.transportCostIncluded,
      tripDurationDays: Math.max(
        1,
        Math.round((new Date(endDate).getTime() - new Date(startDate).getTime()) / 86400000)
      ),
      partySize: seed.travelMode.toLowerCase(),
      activities: seed.activityPreferences,
    }

    const entry: Entry = { categories: {}, groupTips: {} }

    // Generate category advice one batch per category for resilience.
    for (const category of categoriesWithQuestions) {
      const subQuestions = getSubQuestions(category)
      try {
        const records = await LLMAdapter.generateAdviceBatch(cacheKey, [{ category, subQuestions }])
        const record = records.find((r) => r.category === category)
        const answers = (record?.answers as Record<string, string> | undefined) ?? {}

        // Store answers keyed by the EXACT current question text.
        const catAnswers: Record<string, string> = {}
        for (const question of subQuestions) {
          const a = findAnswer(answers, question)
          if (a) catAnswers[question] = a
        }
        if (Object.keys(catAnswers).length > 0) {
          entry.categories[category] = catAnswers
        }
        console.log(`  ✓ ${category} (${Object.keys(catAnswers).length}/${subQuestions.length})`)
      } catch (err) {
        console.error(`  ✗ ${category}: ${(err as Error).message}`)
      }
    }

    // Generate group headline tips, using the freshly generated answers as context.
    try {
      const groups = getGroupQuestions()
      const tips = await LLMAdapter.generateGroupTips(cacheKey, groups, entry.categories)
      entry.groupTips = tips
      console.log(`  ✓ group tips (${Object.keys(tips).length}/${groups.length})`)
    } catch (err) {
      console.error(`  ✗ group tips: ${(err as Error).message}`)
    }

    output[seed.destination] = entry
  }

  // ─── Write the generated TS module ─────────────────────────────────────────
  const header = `/**
 * Pre-generated LLM advice for the /demo trips.
 *
 * ⚠️ AUTO-GENERATED by \`npm run generate-demo-advice\` (scripts/generate-demo-advice.ts).
 * Do not edit by hand — re-run the script to refresh the content.
 *
 * The demo prefers these real answers. Any category/question not present here
 * (e.g. newly added or reworded questions) falls back to the example patterns
 * in demo-data.ts, so the demo always stays complete.
 *
 * Keyed by destination → { categories: { [category]: { [question]: answer } },
 *                          groupTips: { [groupId]: tip } }.
 */

export interface DemoAdviceEntry {
  categories: Record<string, Record<string, string>>
  groupTips: Record<string, string>
}

export const DEMO_ADVICE_GENERATED: Record<string, DemoAdviceEntry> = `

  const body = JSON.stringify(output, null, 2)
  const contents = `${header}${body}\n`

  const outPath = path.join(process.cwd(), 'src', 'lib', 'demo-advice.generated.ts')
  await writeFile(outPath, contents, 'utf8')

  console.log(`\nWrote ${outPath}`)
  console.log('Done.')
  process.exit(0)
}

main().catch((err) => {
  console.error('Fatal error:', err)
  process.exit(1)
})
